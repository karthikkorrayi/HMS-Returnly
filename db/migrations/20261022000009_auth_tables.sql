-- HMS Returnly — sign-in tables for Better Auth (Railway only; Supabase keeps
-- its own Auth until launch, so this file has no copy in supabase/migrations).
-- See docs/AUTH_SPIKE_REPORT.md §3, conditions 1, 2 and 8.
--
-- * Lives in schema auth, NOT public: the Supabase-style default grants on
--   public would otherwise give anon/authenticated access to password hashes.
-- * Extends the existing auth.users (id only, referenced by public.staff)
--   instead of adding a second user table.
-- * Only the auth_service login may read or write these tables; anon,
--   authenticated and app_user get nothing.
-- * Ids are UUIDs generated by the app (crypto.randomUUID()).
-- Run by the migration runner as app_owner, after db/bootstrap/000_platform.sql.

do $$
begin
  if not exists (select from pg_roles where rolname = 'auth_service') then
    raise exception 'Role auth_service is missing: re-run db/bootstrap/000_platform.sql as a superuser first.';
  end if;
end $$;

alter table auth.users
  add column name             text        not null default '',
  add column email            text        not null default '',
  add column email_verified   boolean     not null default false,
  add column image            text,
  add column created_at       timestamptz not null default now(),
  add column updated_at       timestamptz not null default now(),
  add column username         text,
  add column display_username text;
create unique index users_email_key on auth.users (email) where email <> '';
create unique index users_username_key on auth.users (username);
comment on table auth.users is
  'Staff logins (Better Auth user table). public.staff.user_id references id.';

create table auth.session (
  id          uuid primary key,
  user_id     uuid not null references auth.users (id) on delete cascade,
  token       text not null unique,
  expires_at  timestamptz not null,
  ip_address  text,
  user_agent  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index session_user_idx on auth.session (user_id);
create index session_expires_idx on auth.session (expires_at);

create table auth.account (
  id                        uuid primary key,
  user_id                   uuid not null references auth.users (id) on delete cascade,
  account_id                text not null,
  provider_id               text not null,
  access_token              text,
  refresh_token             text,
  id_token                  text,
  access_token_expires_at   timestamptz,
  refresh_token_expires_at  timestamptz,
  scope                     text,
  password                  text,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now()
);
create index account_user_idx on auth.account (user_id);
comment on column auth.account.password is 'scrypt hash, never the password';

create table auth.verification (
  id          uuid primary key,
  identifier  text not null,
  value       text not null,
  expires_at  timestamptz not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table auth.rate_limit (
  id            uuid primary key,
  key           text not null unique,
  count         integer not null,
  last_request  bigint not null
);

revoke all on auth.users, auth.session, auth.account, auth.verification, auth.rate_limit from public;
grant select, insert, update, delete
  on auth.users, auth.session, auth.account, auth.verification, auth.rate_limit
  to auth_service;
